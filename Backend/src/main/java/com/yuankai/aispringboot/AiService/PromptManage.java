    /**
     * 情绪分析输出字段说明。
     * 日记分析与咨询会话分析共用同一份字段定义，避免两处 prompt 随时间漂移
     * （字段含义一旦不一致，会得到两套互不兼容的 JSON）。
     */
    private static final String EMOTION_ANALYSIS_FIELD_SPEC = """
            字段说明：
            - primaryEmotion：最主要情绪，用 2-4 个汉字概括，如「焦虑」「平静」「开心」「疲惫」
            - emotionScore：情绪积极程度，0-100 的整数，越高越积极（负面情绪取低分）
            - isNegative：是否为负面情绪
            - riskLevel：风险等级，0-正常，1-需关注，2-需心理疏导，3-危机（出现自伤或轻生念头时必须为 3）
            - keywords：从内容中提取 3-6 个情绪相关关键词
            - suggestion：一句温和、具体、不说教的话，30 字以内
            - icon：一个最能代表该情绪的 emoji
            - label：情绪的简短标签，与 primaryEmotion 呼应
            - riskDescription：风险等级的中文描述，如「情绪稳定」「需要关注」「需要心理疏导」
            - improvementSuggestions：2-4 条可立即执行的具体行动建议，每条 15 字以内

            """;

